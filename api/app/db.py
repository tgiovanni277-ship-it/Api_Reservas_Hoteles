from contextlib import contextmanager
from pathlib import Path
import sqlite3

from flask import current_app


ROOM_NUMBERS = [
    f"{floor}{room:02d}"
    for floor in range(1, 5)
    for room in range(1, 21)
]


class PostgresCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    @property
    def rowcount(self):
        return self._cursor.rowcount


class PostgresConnection:
    is_postgres = True

    def __init__(self, connection):
        self._connection = connection

    def execute(self, statement, parameters=()):
        statement = statement.strip()
        if statement.upper() == "BEGIN IMMEDIATE":
            # Psycopg abre la transacción en la primera consulta; el bloqueo por fila
            # se adquiere justo después en bloquear_habitacion().
            return None
        statement = statement.replace("?", "%s")
        is_insert = statement.lstrip().upper().startswith("INSERT")
        if is_insert and " RETURNING " not in statement.upper():
            statement += " RETURNING id"

        cursor = self._connection.cursor()
        cursor.execute(statement, parameters)
        lastrowid = None
        if is_insert:
            row = cursor.fetchone()
            if row is not None:
                lastrowid = row["id"]
        return PostgresCursor(cursor, lastrowid)


def _seed_rooms(connection, postgres=False):
    for room_number in ROOM_NUMBERS:
        floor = int(room_number[0])
        if postgres:
            connection.execute(
                "INSERT INTO habitaciones (numero, piso, activa) VALUES (%s, %s, TRUE) "
                "ON CONFLICT (numero) DO NOTHING",
                (room_number, floor),
            )
        else:
            connection.execute(
                "INSERT INTO habitaciones (numero, piso, activa) VALUES (?, ?, 1) "
                "ON CONFLICT(numero) DO NOTHING",
                (room_number, floor),
            )


def init_db(database_path=None, database_url=None):
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        with psycopg.connect(database_url, row_factory=dict_row) as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS usuarios (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre TEXT NOT NULL,
                    correo TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    role TEXT NOT NULL DEFAULT 'user' CHECK (role = 'user'),
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS reservas_hotel (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    huesped TEXT NOT NULL,
                    correo TEXT NOT NULL,
                    habitacion TEXT NOT NULL,
                    fecha_entrada TEXT NOT NULL,
                    fecha_salida TEXT NOT NULL,
                    numero_huespedes INTEGER NOT NULL CHECK (numero_huespedes > 0),
                    estado TEXT NOT NULL CHECK (
                        estado IN ('pendiente', 'confirmada', 'cancelada')
                    ),
                    user_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS habitaciones (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    numero TEXT NOT NULL UNIQUE,
                    piso INTEGER NOT NULL,
                    activa BOOLEAN NOT NULL DEFAULT TRUE
                )
                """
            )
            _seed_rooms(connection, postgres=True)
        return

    database_path = Path(database_path)
    database_path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(database_path)
    try:
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS usuarios (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                nombre TEXT NOT NULL,
                correo TEXT NOT NULL UNIQUE COLLATE NOCASE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'user' CHECK (role = 'user'),
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS reservas_hotel (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                huesped TEXT NOT NULL,
                correo TEXT NOT NULL,
                habitacion TEXT NOT NULL,
                fecha_entrada TEXT NOT NULL,
                fecha_salida TEXT NOT NULL,
                numero_huespedes INTEGER NOT NULL CHECK (numero_huespedes > 0),
                estado TEXT NOT NULL CHECK (
                    estado IN ('pendiente', 'confirmada', 'cancelada')
                ),
                user_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL
            )
            """
        )
        columns = {
            row[1]
            for row in connection.execute("PRAGMA table_info(reservas_hotel)")
        }
        if "user_id" not in columns:
            connection.execute(
                "ALTER TABLE reservas_hotel ADD COLUMN user_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL"
            )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS habitaciones (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                numero TEXT NOT NULL UNIQUE,
                piso INTEGER NOT NULL,
                activa INTEGER NOT NULL DEFAULT 1
            )
            """
        )
        _seed_rooms(connection)
        connection.commit()
    finally:
        connection.close()


@contextmanager
def get_db():
    database_url = current_app.config.get("DATABASE_URL")
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(database_url, row_factory=dict_row)
        try:
            yield PostgresConnection(connection)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()
        return

    connection = sqlite3.connect(current_app.config["DATABASE"])
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()
